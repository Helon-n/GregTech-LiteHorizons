"""Large Naquadah reactor data, including the user's pinned instance overrides."""
import hashlib
import json
import re


def generate(imp, root, split_args):
    label='goodgenerator/loader/FuelRecipeLoader.java'
    raw=(imp.source/label).read_text(encoding='utf-8')
    config_label='goodgenerator/main/GGConfigLoader.java'
    config=(imp.source/config_label).read_text(encoding='utf-8')
    path=imp.instance/'.minecraft/config/GoodGenerator.cfg'
    override=path.read_text(encoding='utf-8') if path.exists() else ''
    settings={m[1]:int(m[2]) for m in re.finditer(r'I:"([^"]+)"\s*=\s*(-?\d+)',override)}
    def array(key):
        values=[int(v.replace('_','')) for v in split_args(re.search(r'\b'+key+r'\s*=\s*new int\[\]\s*\{([^}]+)\}',config)[1])]
        pattern=key+r'\[(\d+)\]\s*=\s*GG_Config\s*\.get\("LargeNaquadahReactor",\s*"([^"]+)"'
        for m in re.finditer(pattern,config):values[int(m[1])]=settings.get(m[2],values[int(m[1])])
        return values
    voltage,time,coolant,excited=[array(k) for k in ['NaquadahFuelVoltage','NaquadahFuelTime','CoolantEfficiency','ExcitedLiquidCoe']]
    if min(voltage+time+coolant+excited)<=0:raise ValueError('Unsupported nonpositive Large Naquadah reactor setting')
    inputs=split_args(re.search(r'FluidStack\[\] inputs\s*=\s*new FluidStack\[\]\s*\{(.*?)\};',raw,re.S)[1])
    outputs=split_args(re.search(r'FluidStack\[\] outputs\s*=\s*new FluidStack\[\]\s*\{(.*?)\};',raw,re.S)[1])
    imp.active_file=label;imp.constants={};used=set()
    def stack(expr):
        id=imp.stack(expr)[0];used.add(id);return id
    for i,(a,b) in enumerate(zip(inputs,outputs)):
        r=imp.emit_recipe('generateLargeNaquadah',{stack(a):1},{stack(b):1},time[i],0,54,{}, {},[],None)
        if r:r.update(stage=8,largeNaquadah=True,generationPower=voltage[i])
    imp.skipped=[s for s in imp.skipped if not(s.get('file')==label and s.get('reason')=='unsupported map naquadahReactorFuels')]
    data={'air':[stack('Materials.LiquidAir.getFluid(1)'),max(0,settings.get('Liquid Air Consumption Per Second',2400))],
      'coolants':[[stack(e),n,v] for e,n,v in zip(['Materials.Time.getMolten(1)','FluidRegistry.getFluidStack("cryotheum",1)','Materials.SuperCoolant.getFluid(1)','GTModHandler.getIC2Coolant(1)'],[20,1000,1000,1000],coolant)],
      'exciters':[[stack(e),n,v] for e,n,v in zip(['Materials.Space.getMolten(1)','GGMaterial.atomicSeparationCatalyst.getMolten(1)','Materials.Naquadah.getMolten(1)','Materials.Uranium235.getMolten(1)','Materials.Caesium.getMolten(1)'],[20,20,20,180,180],excited)],
      'controller':stack('ItemList.LargeNaquadahReactor.get(1)'),
      'maxPower':max(voltage)*max(coolant)*max(excited)//100,
      'sourceFiles':{}}
    for name in [label,config_label,'gregtech/common/tileentities/machines/multi/MTELargeNaquadahReactor.java']:
        digest=hashlib.sha256((imp.source/name).read_bytes()).hexdigest();imp.paths[name]=digest;data['sourceFiles'][name]=digest
    if path.exists():data['sourceFiles']['instance/config/GoodGenerator.cfg']=hashlib.sha256(path.read_bytes()).hexdigest()
    (root/'src/data/naquadah-reference.js').write_text('// Generated by scripts/gtnh-naquadah.py.\nexport const NAQUADAH_REFERENCE='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    return used
