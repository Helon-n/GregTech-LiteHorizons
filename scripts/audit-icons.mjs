import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {CATALOG} from '../src/data/catalog.js';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export function auditIcons(catalog=CATALOG,directory=path.join(root,'src/assets/gtnh')) {
  const filenames=new Set(fs.readdirSync(directory));
  const checked=new Map(),problems=[];
  for(const item of Object.values(catalog.items)) {
    const key=item.icon||item.id;
    if(!checked.has(key)) {
      const file=path.join(directory,`${key}.svg`);
      let reason=null;
      if(!filenames.has(`${key}.svg`)) reason=fs.existsSync(file)?'filename-case':'missing';
      else {
        const svg=fs.readFileSync(file,'utf8');
        if(!/<svg\b/.test(svg)||!/<\/svg>\s*$/.test(svg)) reason='invalid-svg';
        else if(/<image\b|data:image\//i.test(svg)) reason='embedded-bitmap';
        else if(!/<(?:path|rect|polygon|circle|ellipse|line|polyline)\b/.test(svg)) reason='empty';
      }
      checked.set(key,reason);
    }
    if(checked.get(key)) problems.push({id:item.id,name:item.name,icon:key,reason:checked.get(key),...(item.nativeItem?{registry:item.nativeItem.registry,meta:item.nativeItem.meta}: {})});
  }
  return {total:Object.keys(catalog.items).length,uniqueIcons:checked.size,affectedItems:problems.length,problems};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const report=auditIcons();
  fs.mkdirSync(path.join(root,'.local'),{recursive:true});
  fs.writeFileSync(path.join(root,'.local/icon-audit.json'),JSON.stringify(report,null,2)+'\n');
  if(process.argv.includes('--write-gaps')) {
    const keys=[...new Set(report.problems.map(p=>p.icon))].sort();
    fs.writeFileSync(path.join(root,'src/data/icon-gaps.js'),
      '// Generated by scripts/audit-icons.mjs --write-gaps. These are unresolved, never substitute another item.\n'+
      'export const ICON_GAPS=new Set('+JSON.stringify(keys,null,2)+');\n');
    fs.writeFileSync(path.join(root,'docs/icon-gaps.json'),JSON.stringify(report,null,2)+'\n');
  }
  console.log(JSON.stringify({total:report.total,uniqueIcons:report.uniqueIcons,affectedItems:report.affectedItems,reasons:report.problems.reduce((counts,p)=>(counts[p.reason]=(counts[p.reason]||0)+1,counts),{})}));
  if(process.argv.includes('--strict')&&report.affectedItems) process.exitCode=1;
}
