"""Pinned GT matter fabrication; runtime recipes are not NEI fixtures.

GTPostLoad's two fake entries describe the recipes actually selected by
MTEMassfabricator.checkRecipe. Read the installation's config, not defaults.
"""
import hashlib
import json
import re


def generate(imp,root,numeric):
    sources={}
    def read(label):
        path=imp.source/label
        sources[label]=hashlib.sha256(path.read_bytes()).hexdigest()
        imp.paths[label]=sources[label]
        return path.read_text(encoding='utf-8')
    runtime='gregtech/common/tileentities/machines/basic/MTEMassfabricator.java'
    text=read(runtime)
    loader='gregtech/loaders/postload/GTPostLoad.java';recipes=read(loader)
    read('gregtech/common/config/MachineStats.java')
    read('gregtech/api/util/OverclockCalculator.java')
    native='gregtech/loaders/preload/LoaderMetaTileEntities.java';registrations=read(native)
    config=imp.instance/'.minecraft/config/GregTech/MachineStats.cfg'
    match=re.search(r'massfabricator\s*\{([^}]+)\}',config.read_text(encoding='utf-8'))
    if not match:raise ValueError('missing instance massfabricator section')
    def setting(key):
        value=re.search(r'\b[IB]:'+key+r'\s*=\s*(\w+)',match[1])
        if not value:raise ValueError('missing massfabricator setting '+key)
        return value[1]=='true' if value[1] in ('true','false') else int(value[1])
    ticks=setting('durationMultiplier');bonus=setting('UUASpeedBonus');amount=setting('UUAPerUUM');requires=setting('requiresUUA')
    power=numeric(re.search(r'\bBASE_EUT\s*=\s*([^;]+);',text)[1])
    if min(ticks,bonus,amount,power)<1 or ticks//bonus<1:raise ValueError('unsupported nonpositive matter fabrication configuration')
    if '.setEUtIncreasePerOC(2.0)' not in text or '.setMaxOverclocks(tier - 1)' not in text:raise ValueError('changed mass fabricator overclock rules')
    if not re.search(r'long maxAmperesIn\(\)\s*\{\s*return 10;',text):raise ValueError('changed mass fabricator amperage')
    if 'V[mTier] * 512L' not in text:raise ValueError('changed mass fabricator capacity')
    imp.constants={};imp.active_file=loader
    uum=imp.material('UUMatter');uua=imp.material('UUAmplifier')
    controllers=[]
    codes=['LV','MV','HV','EV','IV','LuV','ZPM','UV','UHV','UEV','UIV','UMV']
    for tier,code in enumerate(codes,1):
        key='Machine_'+code+'_Massfab' if tier<=5 else 'MassFabricator'+code
        if not re.search(r'ItemList\.'+key+r'\.set\(\s*new MTEMassfabricator\(',registrations):raise ValueError('unregistered mass fabricator '+key)
        controllers.append({'tier':tier,'code':code,'item':imp.named(key)})
    for boosted in (False,True):
        if requires and not boosted:continue
        marker='MTEMassfabricator.'+('uuaRecipe' if boosted else 'nonUUARecipe')+' ='
        # Empty input is intentional: electricity is the entire raw material.
        r=imp.emit_recipe('massFabricate',{uua:amount} if boosted else {},{uum:1},ticks//bonus if boosted else ticks,power,recipes.count('\n',0,recipes.index(marker))+1,{}, {},[],1 if boosted else None)
        if r:r.update(stage=2,matterFabrication=True)
    reference={'power':power,'ticks':ticks,'amplifiedTicks':ticks//bonus,'amplifier':uua,'matter':uum,'amplifierAmount':amount,'requiresAmplifier':requires,'inputAmps':10,'recipeAmps':8,'bufferTicks':512,'controllers':controllers,'sourceFiles':sources,'config':{'path':str(config),'sha256':hashlib.sha256(config.read_bytes()).hexdigest()},'adaptation':['Recipe selection explicitly chooses amplified or unamplified production; amplifier is not silently substituted.','Logical fluid ports replace the built-in tank; outputs still need physical containers.']}
    (root/'src/data/matter-reference.js').write_text('// Generated by scripts/gtnh-matter.py.\nexport const MATTER_REFERENCE='+json.dumps(reference,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    return {uum,uua,*(row['item'] for row in controllers)}
