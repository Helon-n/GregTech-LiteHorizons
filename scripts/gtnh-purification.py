"""Waterline dynamic I/O reference from the pinned GT source (no game launch)."""
import hashlib
import json
import re


def generate(imp, root, split_args, matching):
    label='gregtech/loaders/postload/chains/PurifiedWaterRecipes.java'
    raw=(imp.source/label).read_text(encoding='utf-8')
    imp.active_file=label
    imp.constants={'duration':'2400','extraBaryonicOutput':'500','BASE_CHANCE':'PurificationPlantBaseChanceKey.INSTANCE'}
    # Re-expand bounded ozonation and catalyst-alignment loops. Other builders
    # are deduplicated by the importer. Fake NEI entries remain excluded.
    resolved=set()
    for m in re.finditer(r'GTValues\.RA\.stdBuilder\(\)',raw):
        body=raw[m.end():raw.index(';',m.end())]
        if '.fake()' in body:continue
        line=raw.count('\n',0,m.start())+1
        skipped_before=len(imp.skipped)
        if 'catalystInputs[i]' in body:
            for i,name in enumerate(['Up','Down','Bottom','Top','Strange','Charm']):
                imp.constants['i']=str(i)
                imp.parse_builder(body.replace('catalystInputs[i]',f'ItemList.Quark_Creation_Catalyst_{name}.get(1)'),line,label)
            if len(imp.skipped)==skipped_before:resolved.add(line)
        elif 'purificationOzonationRecipes' in body:
            for tier in range(1,5):
                imp.constants['tier']=str(tier);imp.parse_builder(body,line,label)
            if len(imp.skipped)==skipped_before:resolved.add(line)
        elif 'purification' in body:
            before=len(imp.recipes);imp.parse_builder(body,line,label)
            if len(imp.recipes)>before:resolved.add(line)
    imp.skipped=[e for e in imp.skipped if not(e.get('file')==label and e.get('line') in resolved)]
    used=set()
    def stack(s):
        id=imp.stack(s)[0];used.add(id);return id
    def mat(s,p='fluid'):return stack(f'Materials.{s}.get'+{'fluid':'Fluid','gas':'Gas','molten':'Molten','plasma':'Plasma','dust':'Dust'}[p]+'(1)')
    def itm(s):return stack('ItemList.'+s+'.get(1)')
    controllers=[itm('Machine_Multi_Purification'+s) for s in ['Plant','UnitClarifier','UnitOzonation','UnitFlocculator','UnitPhAdjustment','UnitPlasmaHeater','UnitUVTreatment','UnitDegasifier','UnitParticleExtractor']]
    lenses=[stack(s) for s in ['GGMaterial.orundum.get(OrePrefixes.lens,1)',*[f'GTOreDictUnificator.get(OrePrefixes.lens,Materials.{m},1)' for m in ['Amber','InfusedAir','Emerald','ManaDiamond','BlueTopaz','Amethyst']],'WerkstoffLoader.FluorBuergerit.get(OrePrefixes.lens,1)','GTOreDictUnificator.get(OrePrefixes.lens,Materials.Dilithium,1)']]
    data={'cycleTicks':2400,'controllers':controllers,'waters':['water',*[mat('Grade'+str(i)+'PurifiedWater') for i in range(1,9)]],
      'distilled':'distilledWater','filter':itm('ActivatedCarbonFilterMesh'),'filterDamage':20,
      'pac':mat('PolyAluminiumChloride'),'waste':mat('FlocculationWasteLiquid'),'alkaline':mat('SodiumHydroxide','dust'),'acid':mat('HydrochloricAcid'),
      'plasma':mat('Helium','plasma'),'coolant':mat('SuperCoolant'),'lenses':lenses,
      'gases':[[mat('Helium','gas'),10000],*[ [stack(f'WerkstoffLoader.{m}.getFluidOrGas(1)'),n] for m,n in [('Neon',7500),('Krypton',5000),('Xenon',2500)]]],
      'superconductors':[[mat('Superconductor'+m+'Base','molten'),1440,1+i*.25] for i,m in enumerate(['UV','UHV','UEV','UIV','UMV'])],
      'neutronium':mat('Neutronium','molten'),'infinity':mat('Infinity','molten'),
      'catalysts':[itm('Quark_Creation_Catalyst_'+m) for m in ['Up','Down','Bottom','Top','Strange','Charm']],
      'baryonic':mat('StableBaryonicMatter'),'source':label,'sha256':hashlib.sha256(raw.encode()).hexdigest()}
    used.update(['water','distilledWater'])
    data['sourceHashes']={label:hashlib.sha256(raw.encode()).hexdigest()}
    for path in sorted((imp.source/'gregtech/common/tileentities/machines/multi/purification').glob('*.java')):
        name=str(path.relative_to(imp.source)).replace('\\','/');digest=hashlib.sha256(path.read_bytes()).hexdigest()
        data['sourceHashes'][name]=digest;imp.paths[name]=digest
    (root/'src/data/purification-reference.js').write_text('// Generated by scripts/gtnh-purification.py.\nexport const PURIFICATION_REFERENCE='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    return used
