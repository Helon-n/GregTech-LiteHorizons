"""Pinned cultures, biological fluids, vat glass and radiation hatch fuels.

The importer retains culture, glass and radiation requirements for the dedicated
vat runtime. Dynamic DNA modules and unknown materials remain unresolved.
"""
import hashlib
import json
import math
import re
import zipfile


def load(imp, root, registered_fluids, split_args, matching):
    def read(label, path=None):
        path = path or imp.source / label
        imp.paths[label] = hashlib.sha256(path.read_bytes()).hexdigest()
        return path.read_text(encoding='utf-8')

    # Hash the original registration and check each texture in its installed jar.
    external = [
        ('Galacticraft-3.4.37-GTNH.jar', 'fluid-metadata/micdoodle8/mods/galacticraft/planets/mars/MarsModule.java',
         [('bacterialsludge', 'bacterialSludge', '细菌泥', 'assets/galacticraftmars/textures/blocks/sludge_still.png')]),
        ('gendustry-1.9.13-GTNH.jar', 'fluid-metadata/net/bdew/gendustry/config/Fluids$.java',
         [('mutagen', 'mutagen', '诱变剂', 'assets/gendustry/textures/blocks/fluids/mutagen/still.png')]),
        ('binnie-mods-2.6.51.jar', 'binnie-2.6.51/binnie/genetics/item/GeneticLiquid.java',
         [('binnie.'+key.lower(), 'genetics'+key[0].upper()+key[1:].replace('.', ''), title,
           'assets/genetics/textures/blocks/liquids/'+key+'.png')
          for key, title in [('growthMedium', '生长培养基'), ('bacteria', '细菌'),
                             ('bacteriaPoly', '聚合细菌'), ('dna.raw', '原始 DNA'),
                             ('bacteriaVector', '载体细菌')]])]
    for jar_name, label, fluids in external:
        jar = imp.instance / '.minecraft/mods' / jar_name
        read('offline/'+label, root/'.local/gtnh-technology'/label)
        imp.paths['instance/mods/'+jar_name] = hashlib.sha256(jar.read_bytes()).hexdigest()
        with zipfile.ZipFile(jar) as archive:
            for registry, id, title, texture in fluids:
                if texture not in archive.namelist():
                    raise ValueError('missing original biology fluid texture '+texture)
                registered_fluids[registry] = (id, title, texture)

    domain = imp.mod_ids['BartWorks']
    loader_label = 'NewHorizonsCoreMod/com/dreammaster/bartworksHandler/BioItemLoader.java'
    loader = read(loader_label, imp.core/'com/dreammaster/bartworksHandler/BioItemLoader.java')
    read('bartworks/common/items/SimpleSubItemClass.java')
    read('bartworks/common/loaders/BioItemList.java')
    read('bartworks/common/loaders/BioLabLoader.java')
    read('bartworks/common/items/ItemLabParts.java')
    read('bartworks/util/BioCulture.java')
    imp.bio_items = {}
    for meta, (key, title) in enumerate([('Collagen', '胶原蛋白'), ('Gelatin', '明胶'), ('Agar', '琼脂')]):
        native = {'registry':domain+':GTNHBioItems', 'meta':meta, 'name':title,
                  'texture':'assets/'+domain.lower()+'/textures/items/item'+key+'.png'}
        imp.bio_items[meta] = native
        imp.external_item_metadata[(native['registry'], meta)] = native

    imp.bio_fluids = {}
    for index, match in enumerate(re.finditer(r'GTFluidFactory.builder\("(\w+)"\)(.*?)(?=GTFluidFactory.builder|};)', loader, re.S)):
        key, body = match.groups()
        color = re.search(r'new short\[\]\s*\{\s*(\d+),\s*(\d+),\s*(\d+)\s*}', body)
        title = re.search(r'withDefaultLocalName\("([^"]+)"\)', body)
        if not color or not title:
            raise ValueError('unresolved biology fluid definition '+key)
        id = 'bioFluid_'+key
        imp.bio_fluids[index] = id
        imp.items[id] = {'id':id, 'name':title[1], 'kind':'fluid', 'category':'流体',
                        'nativeItem':{'registry':key.lower(), 'meta':0,
                         'texture':'assets/gregtech/textures/blocks/fluids/fluid.molten.autogenerated.png',
                         'color':''.join(f'{int(v):02x}' for v in color.groups())}}
    fluid_loader=read('bartworks/common/loaders/FluidLoader.java')
    fluid_array=re.search(r'BioLabFluidMaterials\s*=\s*new Fluid\[\]\s*\{(.*?)};',fluid_loader,re.S)
    imp.bio_lab_fluids={};imp.bio_registered={}
    for index,match in enumerate(re.finditer(r'createAndRegisterFluid\("([^"]+)",\s*new Color\((\d+),\s*(\d+),\s*(\d+)\)\)',fluid_array[1])):
        key,r,g,b=match.groups();id='bioLabFluid_'+key
        imp.bio_lab_fluids[index]=id;imp.bio_registered[key.lower()]=id
        imp.items[id]={'id':id,'name':key,'kind':'fluid','category':'流体','nativeItem':{
            'registry':key.lower(),'meta':0,'color':''.join(f'{int(v):02x}' for v in (r,g,b)),
            'texture':'assets/gregtech/textures/blocks/fluids/fluid.molten.autogenerated.png'}}

    imp.bio_cultures = {}
    cultures = read('bartworks/API/enums/BioCultureEnum.java')
    for match in re.finditer(r'^\s*(\w+)\("([^"]+)",\s*(\d+),\s*EnumRarity\.', cultures, re.M):
        key, name, _ = match.groups()
        end = matching(cultures, cultures.index('(', match.start()))
        args = split_args(cultures[cultures.index('(', match.start())+1:end])
        item = args[-1].split('.')[-1]
        imp.bio_cultures[key] = item
        imp.itemlist[item] = {'registry':domain+':BioLabParts', 'meta':0,
                              'name':name+'培养皿', 'texture':'assets/'+domain.lower()+'/textures/items/petriDish.png',
                              'nbt':{'Name':name}}
    aliases = read('bartworks/common/loaders/BioCultureLoader.java')
    imp.bio_culture_aliases = dict(re.findall(r'BioCultureLoader\.(\w+)\s*=\s*BioCultureEnum\.(\w+)\.bioCulture', aliases))
    # Empty parts must remain distinct from the NBT-bearing cultures.
    for meta, (key, texture, title) in enumerate([
        ('EmptyPetriDish', 'petriDish', '空培养皿'), ('EmptyDNAFlask', 'DNASampleFlask', '空 DNA 样品瓶'),
        ('EmptyPlasmid', 'PlasmidCell', '空质粒细胞'), ('DetergentPowder', 'DetergentPowder', '洗涤剂粉'),
        ('Agarose', 'Agarose', '琼脂糖'), ('PlasmaMembrane', 'PlasmaMembrane', '细胞膜')]):
        imp.itemlist[key] = {'registry':domain+':BioLabParts', 'meta':meta, 'name':title,
                             'texture':'assets/'+domain.lower()+'/textures/items/'+texture+'.png'}

    registration = read('bartworks/common/loaders/recipes/CraftingRecipes.java')
    ids = dict(re.findall(r'^\s*(\w+)\(([\d_]+)\)', read('gregtech/api/enums/MetaTileEntityIDs.java'), re.M))
    controllers = []
    imp.bio_machines = {}
    for match in re.finditer(r'new MTEBioLab\((\w+)\.ID,\s*"([^"]+)",\s*"",\s*(\d+)\)\.getStackForm\(1L\)', registration):
        key, registry, tier = match.groups()
        native = {'registry':'gregtech:gt.blockmachines', 'meta':int(ids[key].replace('_','')),
                  'name':key.replace('_',' ')+' 生物实验室',
                  'texture':'assets/gregtech/textures/blocks/iconsets/MACHINE_CASING_SOLID_STEEL.png'}
        imp.itemlist[key] = native
        imp.bio_machines[key] = key
        controllers.append({'tier':int(tier), 'code':key.removeprefix('BioLab_'), 'item':'gtItem_'+key})
    read('bartworks/common/tileentities/tiered/MTEBioLab.java')
    vat_source = read('bartworks/common/tileentities/multis/MTEBioVat.java')
    radiation = read('bartworks/common/tileentities/tiered/MTERadioHatch.java')
    read('bartworks/common/loaders/RadioHatchMaterialLoader.java')
    read('bartworks/util/BWUtil.java')
    config = read('bartworks/common/configs/Configuration.java')
    parallel = int(re.search(r'bioVatMaxParallelBonus\s*=\s*([\d_]+)', config)[1].replace('_',''))
    if 'calcMod(storedFluidOutputs.amount) + 1' not in vat_source or '8000D * Math.tanh(-x / 20D)' not in radiation:
        raise ValueError('changed bacterial vat/radiation hatch rules')
    elements = read('gregtech/api/enums/Element.java')
    protons = {key:int(p) for key,p in re.findall(r'^\s*(\w+)\((\d+),', elements, re.M)}
    imp.bio_protons = {key:protons[m['element']] for key,m in imp.materials.items() if m.get('element') in protons}
    imp.bio_protons.update(Naquadah=130, NaquadahEnriched=140, Naquadria=150)

    def decay(level):
        if level == 43:return 5000
        if level == 61:return 4500
        return math.ceil((8000*math.tanh(-level/20)+8000)*1000) if level<=100 else math.ceil(8000*math.tanh(-level/65)+8000)

    fuels = {}
    for key,m in imp.materials.items():
        level = imp.bio_protons.get(key,0)
        if key in ('Tritanium',) or level < 83 or not m.get('metal'):continue
        for form,mass in [('stick',1),('stickLong',2)]:
            id = imp.material(key,form)
            fuels[id] = {'sievert':level, 'mass':mass, 'decayTicks':decay(level)}
    for prefix,key in [('RodThorium','Thorium'),('RodNaquadah','NaquadahEnriched'),('RodMOX','Plutonium'),('RodUranium','Uranium'),('RodNaquadria','Naquadria')]:
        for suffix,mass in [('',3),('2',6),('4',12)]:
            id = imp.stack('ItemList.'+prefix+suffix+'.get(1)')[0]
            level = imp.bio_protons[key]
            fuels[id] = {'sievert':level,'mass':mass,'decayTicks':decay(level)}
    for key,title in [('BioVat','细菌培养仓'),('RadioHatch_HV','HV 辐射仓')]:
        imp.itemlist[key] = {'registry':'gregtech:gt.blockmachines','meta':int(ids[key].replace('_','')),
                             'name':title,'texture':'assets/gregtech/textures/blocks/iconsets/MACHINE_CASING_SOLID_STEEL.png'}
    glasses = []
    for key,expression in imp.bw_glass_ores.items():
        code = key.removeprefix('blockGlass')
        tier = ['ULV','LV','MV','HV','EV','IV','LuV','ZPM','UV','UHV','UEV','UIV','UMV','UXV','MAX'].index(code)
        if tier < 3:continue
        glasses.append({'tier':tier,'code':code,'item':imp.stack(expression)[0]})
    reference = {'controllers':controllers,'cultures':imp.bio_cultures,'fuels':fuels,
                 'vat':{'controller':'gtItem_BioVat','hatch':'gtItem_RadioHatch_HV',
                        'casing':imp.named('Casing_CleanStainlessSteel'),'glassCount':32,'glasses':glasses,'maxBonus':parallel},
                 'unsupported':['Dynamic biolab DNA/PCR modules and addon-only radiation materials remain unresolved.'],
                 'adaptations':['Each vat automatically installs one required physical culture and selects a compatible warehouse rod. Shielding follows recipe radiation. No rod is refunded after irradiation starts.',
                                'The configured output container/group is the logical output hatch. Space placement and hatch geometry are not simulated.']}
    imp.bio_controller_keys = [*imp.bio_machines,'BioVat','RadioHatch_HV']
    imp.bio_reference_items = {*fuels,reference['vat']['casing'],*(g['item'] for g in glasses)}
    (root/'src/data/biochemistry-reference.js').write_text(
        '// Generated by scripts/gtnh-biochemistry.py.\nexport const BIOCHEMISTRY_REFERENCE='+
        json.dumps(reference, ensure_ascii=False, separators=(',',':'))+';\n', encoding='utf-8')


def stack(imp, expression, numeric):
    if expression=='ItemRegistry.vat':return imp.named('BioVat'),1
    alias = re.fullmatch(r'BioCultureEnum.getPetriDish\(BioCultureLoader\.(\w+)\)',expression)
    if alias:return imp.named(imp.bio_cultures[imp.bio_culture_aliases[alias[1]]]),1
    culture = re.fullmatch(r'BioCultureEnum.getPetriDish\(BioCultureEnum\.(\w+)\.bioCulture\)', expression)
    if culture:
        return imp.named(imp.bio_cultures[culture[1]]), 1
    item = re.fullmatch(r'newItemStack\(BIOTEMS,([^,]+),([^,]+)\)', expression)
    if item:
        meta = int(numeric(item[2]))
        return imp.stack('getModItem(BartWorks.ID,"GTNHBioItems",'+item[1]+','+str(meta)+')')
    fluid = re.fullmatch(r'newFluidStack\(BIOFLUIDS\[(\d+)\],(.+)\)', expression)
    if fluid:
        return imp.bio_fluids[int(fluid[1])], numeric(fluid[2])
    lab_fluid = re.fullmatch(r'newFluidStack\(FluidLoader.BioLabFluidMaterials\[(\d+)\],(.+)\)',expression)
    if lab_fluid:return imp.bio_lab_fluids[int(lab_fluid[1])],numeric(lab_fluid[2])
    registered = re.fullmatch(r'FluidRegistry.getFluidStack\("([^"]+)",(.+)\)',expression)
    if registered and registered[1] in imp.bio_registered:return imp.bio_registered[registered[1]],numeric(registered[2])
    machine = re.fullmatch(r'newMTEBioLab\((\w+)\.ID,"[^"]+","",\d+\)\.getStackForm\((.+)\)', expression)
    if machine:
        return imp.named(imp.bio_machines[machine[1]]), numeric(machine[2])
    hatch = re.fullmatch(r'newMTERadioHatch\((RadioHatch_HV)\.ID,"[^"]+",StatCollector.translateToLocal\("[^"]+"\),3\)\.getStackForm\((.+)\)',expression)
    if hatch:return imp.named(hatch[1]),numeric(hatch[2])
    return None


def sievert(imp, expression, numeric):
    match = re.fullmatch(r'newSievert\((.+?)(?:,(true|false))?\)',imp.resolve(expression))
    if not match:raise ValueError('unresolved radiation '+expression)
    atom = re.fullmatch(r'BWUtil.calculateSv\((?:Materials\.)?(\w+)\)',match[1])
    level = imp.bio_protons[atom[1]] if atom else numeric(match[1])
    if not isinstance(level,int) or level<0:raise ValueError('invalid radiation '+expression)
    return {'value':level,'exact':match[2]=='true'}
