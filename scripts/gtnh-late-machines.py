"""Pinned Spinmatron structure, physical feeds and operating constants."""
import hashlib
import json
import re


def generate(imp, root, numeric):
    label = 'gregtech/common/tileentities/machines/multi/MTESpinmatron.java'
    text = (imp.source/label).read_text(encoding='utf-8')
    imp.paths[label] = hashlib.sha256(text.encode()).hexdigest()
    casings = (imp.source/'gregtech/api/casing/Casings.java').read_text(encoding='utf-8')
    def casing(key):
        aliases = {'VibrationSafeCasing':'ItemList.Spinmatron_Casing',
                   'SCTurbineCasing':'ItemRefer.SC_Turbine_Casing',
                   'PBIPipeCasing':'ItemList.Casing_Pipe_Polybenzimidazole',
                   'ChamberGrate':'ItemList.Spinmatron_Chamber_Grate',
                   'IsaMillGearboxCasing':'GregtechItemList.Casing_IsaMill_Gearbox',
                   'TurbineShaft':'GregtechItemList.Casing_Turbine_Shaft'}
        if not re.search(r'\b'+key+r'\s*\(', casings): raise ValueError('unresolved Spinmatron casing '+key)
        return imp.stack(aliases[key]+'.get(1)')[0]
    imp.constants = {}
    structure = {}
    for count,key in re.findall(r'\.addCasing\("(\d+(?:-\d+)?)", Casings\.(\w+)\.getLocalizedName', text):
        structure[casing(key)] = int(count.split('-')[-1])
    structure[imp.stack('new ItemStack(Blocks.glass,1)')[0]] = 81
    structure[imp.stack('GregtechItemList.Hatch_Turbine_Rotor.get(1)')[0]] = 8
    controller = imp.named('Machine_Multi_Spinmatron'); structure[controller] = 1
    tiers = []
    for block,frame in [
        ('GTOreDictUnificator.get(OrePrefixes.block,Materials.NaquadahAlloy,1)', 'MaterialsAlloy.PIKYONIUM.getFrameBox(1)'),
        ('getModItem(Avaritia.ID,"Resource_Block",1,0)', 'GTOreDictUnificator.get(OrePrefixes.frameGt,Materials.Neutronium,1)'),
        ('getModItem(Avaritia.ID,"Resource_Block",1,1)', 'GTOreDictUnificator.get(OrePrefixes.frameGt,Materials.Infinity,1)'),
        ('GTOreDictUnificator.get(OrePrefixes.block,Materials.WhiteDwarfMatter,1)', 'GTOreDictUnificator.get(OrePrefixes.frameGt,Materials.SpaceTime,1)'),
    ]:
        tiers.append({imp.stack(block)[0]:56,imp.stack(frame)[0]:9})
    feeds = {tier: imp.stack('CustomItemList.eM_energyMulti64_'+code+'.get(1)')[0]
             for tier,code in [(8,'UV'),(9,'UHV'),(10,'UEV'),(11,'UIV'),(12,'UMV'),(13,'UXV')]}
    fluid = imp.material('BiocatalyzedPropulsionFluid','fluid')
    nanite = imp.named('Hatch_Nanite')
    connectors = {key:imp.stack('CustomItemList.'+key+'.get(1)')[0]
                  for key in ('Hatch_BEC_Connector','Hatch_LineOfSight_Connector')}
    kerosene=imp.stack('new FluidStack(GTPPFluids.Kerosene,1)')[0]
    result = {'controller':controller,'structure':structure,'tiers':tiers,'feeds':feeds,'fluid':fluid,'kerosene':kerosene,
              'naniteHatch':nanite,'connectors':connectors,
              'speed':numeric(re.search(r'BASE_SPEED = ([^;]+)',text)[1]),
              'euMultiplier':numeric(re.search(r'BASE_EU_MODIFIER = ([^;]+)',text)[1]),
              'heavyMultiplier':numeric(re.search(r'HEAVY_MODE_EU_MULTIPLIER = ([^;]+)',text)[1]),
              'fluidPerTier':numeric(re.search(r'FLUID_PER_RECIPE_TIER = ([^;]+)',text)[1]),
              'hash':imp.paths[label]}
    (root/'src/data/late-machines-reference.js').write_text('// Generated by scripts/gtnh-late-machines.py.\nexport const LATE_MACHINES_REFERENCE='+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    return set(structure)|set(feeds.values())|{fluid,kerosene,nanite}|set(connectors.values())|{id for t in tiers for id in t}
