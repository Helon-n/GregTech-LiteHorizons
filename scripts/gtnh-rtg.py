"""Read GT++ RTG pellets and their energy conversion from the pinned source."""
import hashlib
import json
import re
import configparser


def generate(imp,root,split_args,numeric,matching):
    paths=['gtPlusPlus/xmod/gregtech/common/items/MetaGeneratedGregtechItems.java',
      'gtPlusPlus/xmod/gregtech/common/tileentities/generators/MTERTGenerator.java',
      'gtPlusPlus/xmod/gregtech/registration/gregtech/GregtechRTG.java']
    texts=[(imp.source/p).read_text(encoding='utf-8') for p in paths]
    source=texts[0];runtime=texts[1]
    if '20 * 86400 * days' not in runtime or 'Integer.MAX_VALUE' not in runtime:
        raise ValueError('RTG conversion source changed; review formula')
    imp.active_file=paths[0];imp.constants={};used=set();fuels=[]
    controller=imp.stack('GregtechItemList.RTG.get(1)')[0];used.add(controller)
    for match in re.finditer(r'GTValues\.RA\.stdBuilder\(\)((?:(?!GTValues\.RA\.stdBuilder\(\)).)*?\.addTo\(rtgFuels\))',source,re.S):
        code=match[1]
        def arg(method):
            m=re.search(r'\.'+method+r'\(',code)
            if not m:raise ValueError('RTG missing '+method)
            return code[m.end():matching(code,m.end()-1)]
        fuel,n=imp.stack(arg('itemInputs'));used.add(fuel)
        days=split_args(arg('metadata'))[1]
        rounded=re.fullmatch(r'MathUtils\.roundToClosestInt\(([^)]+)\)',days)
        days=int(numeric(rounded[1])+0.5) if rounded else numeric(days)
        power=numeric(arg('eut'));eu=min(2147483647,20*86400*days*power)
        line=source.count('\n',0,match.start())+1
        r=imp.emit_recipe('generateRTG',{fuel:n},{},10,0,line,{}, {},[],None)
        if r:r.update(name=imp.items[fuel]['name']+' · RTG',stage=4,fuelFamily='RTG',fuel=fuel,itemFuel=True,fuelEU=eu,rtg=True,outputRate=power,rtgDays=days)
        fuels.append({'id':fuel,'rate':power,'eu':eu,'days':days})
    if len(fuels)!=5:raise ValueError('Expected five original RTG pellet recipes')
    sources={p:hashlib.sha256((imp.source/p).read_bytes()).hexdigest() for p in paths};imp.paths.update(sources)
    data={'controller':controller,'fuels':fuels,'reserve':512,'cycleTicks':10,'sourceFiles':sources}
    config=imp.instance/'.minecraft/config/IC2.ini'
    settings=configparser.ConfigParser(interpolation=None,strict=False);settings.read(config,encoding='utf-8')
    multiplier=settings.getfloat('balance / energy / generator','radioisotope')
    controller=imp.stack('getModItem(IndustrialCraft2.ID,"blockGenerator",1,6)')[0]
    imp.items[controller]['nativeItem']['texture']='assets/ic2/textures/blocks/generator/blockRTGenerator.png'
    pellet=imp.stack('GTModHandler.getIC2Item("RTGPellets",1)')[0]
    data['ic2']={'controller':controller,'pellet':pellet,'multiplier':multiplier,'slots':6,'capacity':20000,'tier':1,'rates':[0]+[int(2**(n-1)*multiplier) for n in range(1,7)]}
    used|={controller,pellet}
    data['sourceFiles']['instance/config/IC2.ini']=hashlib.sha256(config.read_bytes()).hexdigest()
    for name in ('TileEntityRTGenerator.java','TileEntityBaseGenerator.java'):
        path=root/'.local/gtnh-technology/ic2-2.2.828/ic2/core/block/generator/tileentity'/name
        data['sourceFiles']['IC2-2.2.828/'+name]=hashlib.sha256(path.read_bytes()).hexdigest()
    imp.paths.update(data['sourceFiles'])
    (root/'src/data/rtg-reference.js').write_text('// Generated by scripts/gtnh-rtg.py.\nexport const RTG_REFERENCE='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    return used
