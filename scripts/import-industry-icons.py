            token = re.sub(r'[^a-z]', '', suffix.split('/')[-2] if 'basicmachines' in suffix else suffix.split('/')[-1].replace('.png', '').replace('OVERLAY_FRONT_', '')).lower()
            candidates = [p for p in importer.files if p.startswith(gt) and token in re.sub(r'[^a-z]', '', p.lower()) and p.endswith('.png') and ('OVERLAY_FRONT' in p or 'iconsets' in p) and 'ACTIVE' not in p and 'GLOW' not in p]
