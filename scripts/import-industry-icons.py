            name = item['nativeVanilla']
            name={'bucket':'bucket_empty','water_bucket':'bucket_water','brown_mushroom':'mushroom_brown','porkchop':'porkchop_raw','cooked_porkchop':'porkchop_cooked','beef':'beef_raw','cooked_beef':'beef_cooked','chicken':'chicken_raw','cooked_chicken':'chicken_cooked','fish':'fish_cod_raw','fire_charge':'fireball','packed_ice':'ice_packed','minecart':'minecart_normal','written_book':'book_written','book':'book_normal','map':'map_empty','torch':'torch_on','redstone_torch':'redstone_torch_on','iron_door':'door_iron','glass_bottle':'potion_bottle_empty','golden_carrot':'carrot_golden','golden_apple':'apple_golden','speckled_melon':'melon_speckled','slime_ball':'slimeball','golden_sword':'gold_sword','wooden_sword':'wood_sword','golden_rail':'rail_golden','fermented_spider_eye':'spider_eye_fermented','glass_pane':'glass'}.get(name,name)
